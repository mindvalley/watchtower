'use strict';

// One-off: re-rule every stored composite to the /100 scale.
//
// The engine changed on 2026-08-27 (watchtower#composite-out-of-100).
// The composite used to be a mean out of 5 with a Critical finding forcing the
// badge red without touching the number; it is now a single number out of 100
// with the Critical scaled into it. Everything already stored still carries the
// old rule: 11 current boards and 138 scan_history rows.
//
// Nothing is re-scanned and nothing is re-judged. Both tables keep the full
// per-criterion map, so every reading can be recomputed from what it already
// holds. Of the 115 readings git can reconstruct, exactly one changes colour.
//
// Run:  node scripts/recompute-composite.js            # dry run against the DB
//       node scripts/recompute-composite.js --sql      # emits the migration
//       node scripts/recompute-composite.js --files    # rewrites public/data
//
// --sql because a managed production database is often app-only, the same
// constraint that shaped the scan-history backfill:
//
//   node scripts/recompute-composite.js --sql > /tmp/recompute.sql
//   # then apply /tmp/recompute.sql with whatever your host runs migrations with
//
// It is safe to run twice. Both statements recompute from the criterion map
// rather than transforming the current score, so re-applying is a no-op rather
// than a second scaling — which is the property that makes a "did that run?"
// moment survivable.
//
// TWO IMPLEMENTATIONS, DELIBERATELY. The files path needs JavaScript and the
// production path needs SQL, and neither can call the engine — it ships as a
// GitHub action, not a library. So the rule is written twice, and
// tests/db/recompute-composite.integration.test.js asserts the two agree on
// every row of a real database. Without that test this file would be a place
// for the fleet to quietly drift from its own engine.
//
// The JavaScript half is NOT written here. It is `db/composite.js`, shared with
// the /ingest check that refuses a payload whose composite disagrees with its
// own criteria — one place for this service's understanding of the rule, rather
// than a copy per caller.

const fs = require('fs');
const path = require('path');
const {
  compositeOf, bandFor, CRITICAL_CEILING, RED_MAX, AMBER_MAX,
} = require('../db/composite');

// ── the same rule in SQL ─────────────────────────────────────────────────────
//
// double precision rather than numeric so the arithmetic matches JavaScript's.
// avg() over numeric is exact decimal and would land on the other side of a
// .5 boundary from the engine on some readings; the integration test compares
// the two on real rows precisely because that difference is invisible by
// inspection.
const COMPOSITE_SQL = (scoreExpr, criticalExpr) => `
      round((
        avg(${scoreExpr})
        * 20
        * CASE WHEN bool_or(${criticalExpr}) THEN ${CRITICAL_CEILING} ELSE 1 END
      )::numeric)::int`;

const BAND_SQL = (col) => `
    CASE WHEN ${col} IS NULL THEN NULL
         WHEN ${col} <= ${RED_MAX} THEN 'red'
         WHEN ${col} <= ${AMBER_MAX} THEN 'amber'
         ELSE 'green' END`;

function migrationSql() {
  return `-- Re-rule every stored composite to /100. Generated by
-- scripts/recompute-composite.js --sql; see that file for the rule.
--
-- Recomputes from each row's own criterion map rather than transforming the
-- stored number, so running this twice is a no-op, not a second scaling.
BEGIN;

-- 1. The current board. All eleven systems publish through /ingest, so the
--    database owns these; the committed files are only the empty-database
--    bootstrap and are recomputed separately in the same change.
UPDATE systems s
SET score  = c.new_score,
    colour = ${BAND_SQL('c.new_score')}
FROM (
  SELECT cs.system_id,${COMPOSITE_SQL(
    "(cs.payload->>'score')::double precision",
    "coalesce((cs.payload->>'critical')::boolean, false)",
  )} AS new_score
  FROM criterion_scores cs
  WHERE cs.payload->>'score' IS NOT NULL
  GROUP BY cs.system_id
) c
WHERE s.id = c.system_id;

-- 2. Every reading behind the trend charts.
UPDATE scan_history h
SET score  = c.new_score,
    colour = ${BAND_SQL('c.new_score')}
FROM (
  SELECT h2.id,${COMPOSITE_SQL(
    "(e.value->>'score')::double precision",
    "coalesce((e.value->>'critical')::boolean, false)",
  )} AS new_score
  FROM scan_history h2
  CROSS JOIN LATERAL jsonb_each(h2.criteria) AS e(key, value)
  WHERE e.value->>'score' IS NOT NULL
  GROUP BY h2.id
) c
WHERE h.id = c.id;

-- Post-conditions. A migration that half-works in silence is worse than one
-- that fails, and the failure mode here is specific: an UPDATE ... FROM whose
-- subquery matches fewer rows than expected leaves the rest on the old scale,
-- and an old /5 score is still a perfectly plausible number. Nothing about the
-- stored value would give it away.
--
-- So rather than range-checking, recompute and compare: every row that HAS
-- scored criteria must now hold exactly what the rule produces for it. A row
-- the UPDATE skipped fails this, where a range check would wave it through.
DO $$
DECLARE bad int;
BEGIN
  SELECT count(*) INTO bad FROM (
    SELECT s.id
    FROM systems s
    JOIN criterion_scores cs ON cs.system_id = s.id AND cs.payload->>'score' IS NOT NULL
    GROUP BY s.id, s.score, s.colour
    HAVING s.score IS DISTINCT FROM${COMPOSITE_SQL(
    "(cs.payload->>'score')::double precision",
    "coalesce((cs.payload->>'critical')::boolean, false)",
  )}
  ) q;
  IF bad > 0 THEN RAISE EXCEPTION 'systems: % scored rows were not re-ruled', bad; END IF;

  SELECT count(*) INTO bad FROM (
    SELECT h.id
    FROM scan_history h
    CROSS JOIN LATERAL jsonb_each(h.criteria) AS e(key, value)
    WHERE e.value->>'score' IS NOT NULL
    GROUP BY h.id, h.score, h.colour
    HAVING h.score IS DISTINCT FROM${COMPOSITE_SQL(
    "(e.value->>'score')::double precision",
    "coalesce((e.value->>'critical')::boolean, false)",
  )}
  ) q;
  IF bad > 0 THEN RAISE EXCEPTION 'scan_history: % scored rows were not re-ruled', bad; END IF;

  -- A score with no colour renders as an uncoloured ring; a colour with no
  -- score renders as an empty band. Both have shipped here before.
  SELECT count(*) INTO bad FROM systems WHERE (score IS NULL) <> (colour IS NULL);
  IF bad > 0 THEN RAISE EXCEPTION 'systems: % rows where score and colour disagree about being absent', bad; END IF;
  SELECT count(*) INTO bad FROM scan_history WHERE (score IS NULL) <> (colour IS NULL);
  IF bad > 0 THEN RAISE EXCEPTION 'scan_history: % rows where score and colour disagree about being absent', bad; END IF;
END $$;

COMMIT;
`;
}

// ── the committed files ──────────────────────────────────────────────────────
//
// Every system publishes through /ingest today, so these are not the live
// numbers. They are what an empty database bootstraps from, and what a local
// checkout renders. Leaving them on the old scale would make a fresh clone
// disagree with production, which is the kind of difference that gets found
// during an incident rather than before one.
function rewriteFiles(dataDir) {
  const file = path.join(dataDir, 'benchmark.json');
  const board = JSON.parse(fs.readFileSync(file, 'utf8'));
  const changes = [];
  for (const [key, sys] of Object.entries(board.systems || {})) {
    const next = compositeOf(sys.criteria);
    changes.push({
      key, from: sys.score, fromColour: sys.colour, to: next.score, toColour: next.colour,
    });
    sys.score = next.score;
    sys.colour = next.colour;
  }
  return { file, board, changes };
}

// ── edges ────────────────────────────────────────────────────────────────────

async function dryRun() {
  const { getPool } = require('../db/pool');
  const pool = getPool();
  const { rows } = await pool.query(
    `SELECT s.system_key, s.score, s.colour,
            jsonb_object_agg(cs.criterion_id, cs.payload) FILTER (WHERE cs.id IS NOT NULL) AS criteria
     FROM systems s LEFT JOIN criterion_scores cs ON cs.system_id = s.id
     GROUP BY s.id ORDER BY s.system_key`,
  );
  console.log('system'.padEnd(18), 'stored'.padEnd(14), 'recomputed');
  for (const r of rows) {
    const next = compositeOf(r.criteria || {});
    const stored = `${r.score == null ? '—' : r.score} ${r.colour || ''}`.trim();
    const to = `${next.score == null ? '—' : next.score} ${next.colour || ''}`.trim();
    console.log(r.system_key.padEnd(18), stored.padEnd(14), to,
      r.colour && next.colour && r.colour !== next.colour ? '  COLOUR MOVED' : '');
  }
  const h = await pool.query('SELECT count(*)::int AS n FROM scan_history');
  console.log(`\n${rows.length} systems · ${h.rows[0].n} history rows would be recomputed`);
  await pool.end();
}

async function main() {
  const args = process.argv.slice(2);
  if (args.includes('--sql')) {
    process.stdout.write(migrationSql());
    return;
  }
  if (args.includes('--files')) {
    const dataDir = path.join(__dirname, '..', 'public', 'data');
    const { file, board, changes } = rewriteFiles(dataDir);
    fs.writeFileSync(file, `${JSON.stringify(board, null, 2)}\n`);
    for (const c of changes) {
      console.log(`${c.key.padEnd(18)} ${String(c.from).padEnd(6)} ${(c.fromColour || '').padEnd(6)}`
        + ` ->  ${String(c.to).padEnd(5)} ${c.toColour || ''}`
        + `${c.fromColour !== c.toColour ? '   COLOUR MOVED' : ''}`);
    }
    console.log(`\nrewrote ${file}`);
    return;
  }
  await dryRun();
}

if (require.main === module) {
  main().catch((e) => { console.error(e); process.exit(1); });
}

module.exports = {
  compositeOf, bandFor, migrationSql, rewriteFiles, CRITICAL_CEILING, RED_MAX, AMBER_MAX,
};
